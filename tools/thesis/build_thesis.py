def sign_line(t: Thesis, role: str, name: str, after: float) -> None:
    """인준 서명 줄 — 이름을 밑줄 위에 쓰고, 서명 · 도장 자리 (인)을 남긴다."""
    para = t.centered(f'{role}    ', 15, after=after)
    for text, under in (('\u3000' * 3 + name + '\u3000' * 3, True), ('  (인)', False)):
        r = para.add_run(text)
        r.underline = under
        set_font(r, name=HEAD, size=15)


