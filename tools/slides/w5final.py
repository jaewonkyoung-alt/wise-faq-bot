def flow(s, steps, y, x0=0.55, w=2.2, gap=0.3, h=0.95):
    for i, (hd, b) in enumerate(steps):
        x = x0 + i * (w + gap)
        box(s, x, y, w, h, [(hd, {"bold": True, "size": 12})] + [(l, {"size": 9, "color": GRAY}) for l in b.split("\n")],
            fill=LIGHT if i in (0, len(steps) - 1) else WHITE)
        if i < len(steps) - 1:
            arrow(s, x + w, y + h / 2, x + w + gap, y + h / 2)


